"""How long are this corpus's chunks and queries in jina-colbert-v2's own tokenizer?

WHY THIS RUNS BEFORE ANY ENCODING
---------------------------------
`docs/colbert-late-interaction-notes.md` sizes the whole axis from "Thai at
roughly 2-3 chars/token" and says outright to measure with the real tokenizer
before relying on it. Three decisions ride on the answer, and two of them are
threats to validity rather than engineering details:

  1. **`doc_maxlen`.** The checkpoint's `artifact.metadata` says 300. Every chunk
     longer than that loses its tail -- while the dense arms ColBERT is compared
     against see the whole chunk (bge-m3 8192 ctx, qwen3 32k). That is a handicap
     applied to the treatment only, so the rate has to be reported, not assumed
     small. The model itself is not the constraint: jina-colbert-v2 is rotary and
     the card claims 8192 tokens, so 300 is a convention inherited from ColBERTv2,
     not a limit.
  2. **`query_maxlen`.** ColBERT pads a query *up* to `query_maxlen` with `<mask>`
     (query augmentation) and **truncates** anything longer. The default is 32.
     This project's Gold queries are full Thai questions, not keywords, so 32 is
     the number most likely to be quietly wrong.
  3. **Storage.** tokens x 128 dims x 2 bytes decides whether MaxSim can be
     exhaustive on a 12 GB card or needs an ANN index.

The chars/token figure is reported per chunker because a hand-written probe
sentence is not the corpus: one pure-Thai sentence measures 4.79 chars/token
where the corpus measures ~2.97, so sizing from a probe would have
under-counted tokens by about 60%.

Read-only: reads `chunks.parquet` and the two Gold query sets, downloads the
tokenizer, writes one report.

Run:
    .venv/Scripts/python.exe tools/eval/colbert_length_profile.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq
import yaml

REPO = Path(__file__).resolve().parents[2]
ROOT = REPO / "data" / "index" / "chunker_compare_full"
OUT = REPO / "data" / "results" / "colbert_length_profile.md"
MODEL = "jinaai/jina-colbert-v2"

# Caps to profile. 300 is the checkpoint default; the others are what removing
# the confound would cost. Reported side by side so the choice is made on
# numbers rather than on the default.
DOC_CAPS = [180, 300, 512, 1024]
QUERY_CAPS = [32, 48, 64, 96]
DIM = 128            # full Matryoshka width
BYTES_PER = 2        # fp16 storage

# One combo per chunker. Chunk rows are shared across the 9 embedders for a given
# (loader, chunker) -- `miss_depth_profile.py`'s S3b verifies exactly that -- so
# the embedder in the name is irrelevant here and one ColBERT index per chunker
# would serve every column of the comparison.
COMBOS = {
    "fixed_size": "plain__fixed_size__local__ceea7536",
    "recursive": "plain__recursive__local__0fdddac0",
    "semantic": "plain__semantic__local__834c4336",
    "sentence": "plain__sentence__local__5528285a",
}
QUERY_SETS = {
    "73det (106)": REPO / "config" / "eval" / "gold_query_set_73det.yaml",
    "thematic (179)": REPO / "config" / "eval" / "gold_query_set.yaml",
}

# <s> [Marker] ... </s>
SPECIAL_OVERHEAD = 3


def token_lengths(tok, texts: list[str], batch: int = 4000) -> np.ndarray:
    """Lengths only. Holding 75k full id lists is a few hundred MB of Python ints
    for a number that fits in an int64."""
    out: list[int] = []
    for i in range(0, len(texts), batch):
        enc = tok(texts[i : i + batch], add_special_tokens=False, verbose=False)["input_ids"]
        out.extend(len(x) for x in enc)
    return np.asarray(out, dtype=np.int64)


def main() -> int:
    sys.stdout.reconfigure(errors="replace")
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(MODEL)

    L = [
        "# ColBERT length profile",
        "",
        "Generated by `tools/eval/colbert_length_profile.py` — measured with "
        f"`{MODEL}`'s own tokenizer (`{type(tok).__name__}`, vocab {tok.vocab_size}, "
        f"{len(tok)} with the two ColBERT markers).",
        "",
        "`doc_maxlen`/`query_maxlen` are ColBERT conventions, not model limits: this "
        "checkpoint is rotary and its card claims 8192 tokens. Truncation is therefore a "
        "**choice**, and one applied to the treatment alone — the dense arms it would be "
        "compared against read the whole chunk.",
        "",
    ]

    # ---------------- documents ----------------
    per_chunker: dict[str, np.ndarray] = {}
    L += ["## 1. chunks", "",
          "`tokens` excludes the 3 special tokens (`<s> [DocumentMarker] … </s>`), "
          "which the cap does include.", "",
          "| chunker | rows | chars/token | mean | p50 | p90 | p99 | max |",
          "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for chunker, combo in COMBOS.items():
        path = ROOT / combo / "chunks.parquet"
        if not path.exists():
            L.append(f"| {chunker} | **MISSING** `{path.name}` | | | | | | |")
            continue
        texts = pq.read_table(path, columns=["text"]).column("text").to_pylist()
        lens = token_lengths(tok, texts)
        per_chunker[chunker] = lens
        chars = np.fromiter((len(t) for t in texts), dtype=np.int64, count=len(texts))
        L.append(f"| {chunker} | {len(lens):,} | {chars.sum()/lens.sum():.2f} | "
                 f"{lens.mean():.0f} | {np.percentile(lens,50):.0f} | "
                 f"{np.percentile(lens,90):.0f} | {np.percentile(lens,99):.0f} | "
                 f"{lens.max():,} |")

    L += ["", "### 1b. what each cap costs", "",
          "`truncated` is the share of chunks that lose their tail at that cap — the "
          "confound. `GB` is all four chunkers together at "
          f"{DIM} dims x fp16, i.e. what an exhaustive MaxSim would have to hold.", "",
          "| cap | " + " | ".join(f"{c} truncated" for c in per_chunker) +
          " | tokens (all 4) | GB (all 4) |",
          "|---:|" + "---:|" * (len(per_chunker) + 2)]
    for cap in DOC_CAPS:
        cells, total = [], 0
        for lens in per_chunker.values():
            over = lens + SPECIAL_OVERHEAD > cap
            cells.append(f"{over.mean()*100:.1f}%")
            total += int(np.minimum(lens + SPECIAL_OVERHEAD, cap).sum())
        L.append(f"| {cap} | " + " | ".join(cells) +
                 f" | {total:,} | {total*DIM*BYTES_PER/1024**3:.2f} |")

    # ---------------- queries ----------------
    L += ["", "## 2. queries", "",
          "ColBERT pads a query up to `query_maxlen` with `<mask>` and **truncates** "
          "anything longer, so this cap is a hard ceiling on how much of the question "
          "the model ever sees. It is also the per-query cost: a query is "
          "`query_maxlen` vectors regardless of how short it is.", "",
          "| query set | n | mean | p50 | p90 | max | " +
          " | ".join(f">{c}" for c in QUERY_CAPS) + " |",
          "|---|---:|---:|---:|---:|---:|" + "---:|" * len(QUERY_CAPS)]
    for label, path in QUERY_SETS.items():
        if not path.exists():
            L.append(f"| {label} | **MISSING** `{path.name}` | | | | | | | | |")
            continue
        rows = yaml.safe_load(path.read_text(encoding="utf-8"))
        qs = [r["query"] for r in rows]
        lens = token_lengths(tok, qs)
        over = " | ".join(f"{(lens + SPECIAL_OVERHEAD > c).mean()*100:.0f}%" for c in QUERY_CAPS)
        L.append(f"| {label} | {len(qs)} | {lens.mean():.0f} | {np.percentile(lens,50):.0f} | "
                 f"{np.percentile(lens,90):.0f} | {lens.max()} | {over} |")

    L += ["", "## 3. what this decides", "",
          "Filled in by hand in `docs/colbert-late-interaction-notes.md`; this file is "
          "regenerated by its script and must not carry hand-written conclusions "
          "(`--render` would erase them).", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    print(f"\nwritten to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
