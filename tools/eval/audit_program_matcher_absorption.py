"""How much does `match_programs` absorb names that are not in its dictionary?

Found as a side effect of building the relation graph (2026-08-10): edge A's
whole `ambiguous` row for `หลักสูตรแพทยศาสตรบัณฑิต` turned out to be
`หลักสูตรทันตแพทยศาสตรบัณฑิต` and `หลักสูตรพยาบาลศาสตรบัณฑิต` -- two real,
different programs -- both matching it. `match_programs` has no "matches
nothing" exit for a near miss: it keeps the best candidate in the prefix group
and accepts it at ratio >= 0.82, so a corpus name absent from `programs.json`
is absorbed by its nearest dictionary neighbour rather than rejected.

**This measures the blast radius; it does not fix anything.** The matcher is
read by `build_gold_candidates.py` and by `router.classify_query`, so moving
the threshold would move published numbers -- which is precisely why the size
has to be known first. Scope was already bounded on one side: 0 of the 253
dictionary names collide with *each other* at threshold, so every absorption is
a collision with a name outside the dictionary.

Three questions, in the order that decides whether a fix is worth anything:

  1. CORPUS   how many accepted matches have a span that is not the canonical,
              and how many of those inserted enough text to be a different
              program rather than OCR noise;
  2. QRELS    whether any of it reaches the Gold set;
  3. ROUTER   whether any of it changes a route.

Run (CPU only, one corpus walk ~5 min):
    PYTHONPATH=src python tools/eval/audit_program_matcher_absorption.py
    ... --render     # re-derive the report from the cached walk, no walk

Generated by tools/eval/audit_program_matcher_absorption.py
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from collections import Counter, defaultdict
from datetime import datetime
from difflib import SequenceMatcher
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

from rag_lab.loaders.common import (  # noqa: E402
    iter_corpus_files,
    strip_document_header,
    strip_mapping_tables,
)
from rag_lab.loaders.program_loader import (  # noqa: E402
    _MATCH_THRESHOLD,
    _WINDOW_SLACK,
    _build_scan_pattern,
    _bounded_span_for,
    _by_prefix,
    load_dictionary,
    match_programs,
)
from rag_lab.router import classify_query  # noqa: E402

CORPUS_ROOT = REPO / "academic_resolutions"
RAW_PATH = REPO / "data" / "results" / "program_matcher_absorption_raw.json"
REPORT = REPO / "docs" / "program-matcher-absorption.md"
GOLD = REPO / "config" / "eval" / "gold_query_set_73det.yaml"

# An accepted span that differs from its canonical by this many *inserted*
# characters or more is reported separately from OCR noise. Not a verdict --
# the full distribution is printed so the cut is not load-bearing.
INSERT_FLOOR = 2


def match_programs_detailed(text: str, dictionary=None) -> list[dict]:
    """`match_programs` with its working shown: one record per *accepted*
    match, carrying the span it accepted and the ratio it accepted it at.

    Deliberately a transcription of the original loop rather than a call into
    it -- S1 gates the two against each other on real corpus text, because a
    measurement of a slightly different function measures nothing.
    """
    dictionary = dictionary if dictionary is not None else load_dictionary()
    grouped = _by_prefix(dictionary)
    pattern = _build_scan_pattern(tuple(grouped))
    out: list[dict] = []
    for m in pattern.finditer(text):
        best_canonical, best_ratio, best_span = None, 0.0, ""
        for canonical in grouped[m.group(0)]:
            span = _bounded_span_for(text, m.start(), len(canonical))
            ratio = SequenceMatcher(None, canonical, span).ratio()
            if ratio > best_ratio:
                best_canonical, best_ratio, best_span = canonical, ratio, span
        if best_canonical is not None and best_ratio >= _MATCH_THRESHOLD:
            out.append({"canonical": best_canonical, "span": best_span,
                        "ratio": round(best_ratio, 4)})
    return out


def strip_window_slack(canonical: str, span: str) -> str:
    """Drop the trailing characters the *window*, not the text, put there.

    `_bounded_span_for` reads `len(canonical) + _WINDOW_SLACK` characters, so an
    otherwise perfect span still ends in up to `_WINDOW_SLACK` characters of
    whatever followed the name -- `(กา`, ` จำน`, `(หล`. Counting those as
    inserted text is what the first run of this audit did, and it produced a
    headline of "99.3% of matches absorb a different name" whose mode sat
    exactly at 4 = `_WINDOW_SLACK`. The tail is trimmed to at most that many
    characters, so a genuinely longer name still registers the excess.

    Note what this cannot see: a name differing from its canonical only *after*
    the window ends is invisible to the matcher and therefore to this audit.
    That is a bound on the measurement, not a property of the corpus.
    """
    ops = SequenceMatcher(None, canonical, span).get_opcodes()
    last_equal = max((o for o in ops if o[0] == "equal"), key=lambda o: o[4],
                     default=None)
    if last_equal is None:
        return span
    tail = len(span) - last_equal[4]
    return span[: len(span) - min(tail, _WINDOW_SLACK)]


def inserted_chars(canonical: str, span: str) -> int:
    """Characters present in `span` but absent from `canonical`.

    The discriminator between "OCR misread a character" (a 1-char replace) and
    "this is a different program name" (a multi-char insert such as ทันต or
    พยาบาล). Counts the span side of both `insert` and `replace` opcodes, after
    `strip_window_slack` removes the window's own tail.
    """
    span = strip_window_slack(canonical, span)
    total = 0
    for tag, _i1, _i2, j1, j2 in SequenceMatcher(None, canonical, span).get_opcodes():
        if tag in ("insert", "replace"):
            total += j2 - j1
    return total


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return path.read_text(encoding="utf-8-sig")


def collect() -> dict:
    t0 = time.time()
    files: dict[str, list[dict]] = {}
    for i, path in enumerate(iter_corpus_files(CORPUS_ROOT)):
        text = strip_mapping_tables(strip_document_header(read_text(path)))
        hits = match_programs_detailed(text)
        if hits:
            files[str(path.relative_to(CORPUS_ROOT).as_posix())] = hits
        if i % 300 == 0:
            print(f"  ...{i} files, {time.time() - t0:.0f}s", flush=True)
    return {
        "generated_by": "tools/eval/audit_program_matcher_absorption.py",
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "walk_seconds": round(time.time() - t0, 1),
        "n_files_with_hits": len(files),
        "files": files,
    }


def self_checks(raw: dict) -> list[tuple[str, bool, str]]:
    checks: list[tuple[str, bool, str]] = []

    # S1 -- the instrumented matcher IS the shipped one. Sampled on real
    # corpus text, not a fixture: the transcription could diverge only on
    # inputs the fixture doesn't have.
    sample = [p for p in list(iter_corpus_files(CORPUS_ROOT))[::173]][:15]
    bad = []
    for path in sample:
        text = strip_mapping_tables(strip_document_header(read_text(path)))
        mine = sorted({h["canonical"] for h in match_programs_detailed(text)})
        if mine != match_programs(text):
            bad.append(path.name)
    checks.append(("S1 instrumented matcher == match_programs", not bad,
                   f"{len(sample)} files sampled, {len(bad)} differ"))

    # S2 -- every recorded span really does clear the shipped threshold, and
    # every recorded canonical really is in the dictionary.
    canon = {e["canonical"] for e in load_dictionary()}
    hits = [h for hs in raw["files"].values() for h in hs]
    ok = all(h["ratio"] >= _MATCH_THRESHOLD and h["canonical"] in canon for h in hits)
    checks.append(("S2 every recorded hit is dictionary-canonical and >= threshold",
                   ok, f"{len(hits):,} hits, threshold {_MATCH_THRESHOLD}"))

    # S3 -- an exact-span match must have zero insertions, or `inserted_chars`
    # is measuring the wrong thing and the whole §1 split is noise.
    exact = [h for h in hits if h["span"] == h["canonical"]]
    ok = all(inserted_chars(h["canonical"], h["span"]) == 0 for h in exact)
    checks.append(("S3 inserted_chars == 0 on every exact span", ok,
                   f"{len(exact):,} exact spans"))

    # S4 -- the known instance reproduces. If the two dental/nursing names
    # stopped being absorbed, this audit is about a defect that no longer
    # exists and the counts below would be silently measuring something else.
    target = "หลักสูตรแพทยศาสตรบัณฑิต"
    absorbed = {h["span"] for hs in raw["files"].values() for h in hs
                if h["canonical"] == target and h["span"] != target}
    ok = any("ทันต" in s for s in absorbed) or any("พยาบาล" in s for s in absorbed)
    checks.append(("S4 the motivating instance still reproduces", ok,
                   f"{len(absorbed)} distinct spans absorbed into {target}"))

    # S5 -- the check the first run of this audit did not have, and paid for.
    # `_bounded_span_for` reads len(canonical) + _WINDOW_SLACK characters, so a
    # perfect match still arrives with a tail; counting it made 6,807 matches
    # look like 4-char absorptions when 4 IS the slack. A span that is exactly
    # its canonical plus window tail must score zero, measured against the real
    # spans on disk rather than a fixture.
    slack_only = [h for h in hits
                  if h["span"] != h["canonical"]
                  and h["span"].startswith(h["canonical"])
                  and len(h["span"]) - len(h["canonical"]) <= _WINDOW_SLACK]
    ok = all(inserted_chars(h["canonical"], h["span"]) == 0 for h in slack_only)
    checks.append((f"S5 a pure {_WINDOW_SLACK}-char window tail counts as 0 inserted",
                   ok, f"{len(slack_only):,} slack-only spans"))
    return checks


def render(raw: dict) -> str:
    hits = [h for hs in raw["files"].values() for h in hs]
    # Compare on the trimmed span throughout: the raw span always carries up to
    # `_WINDOW_SLACK` characters the window read past the name, so `span ==
    # canonical` would classify an otherwise-perfect match as a difference.
    for h in hits:
        h["trimmed"] = strip_window_slack(h["canonical"], h["span"])
    exact = [h for h in hits if h["trimmed"] == h["canonical"]]
    inexact = [h for h in hits if h["trimmed"] != h["canonical"]]
    ins = Counter(inserted_chars(h["canonical"], h["span"]) for h in inexact)
    suspicious = [h for h in inexact
                  if inserted_chars(h["canonical"], h["span"]) >= INSERT_FLOOR]

    L = [f"# `match_programs` absorption -- blast radius\n",
         f"Generated by `tools/eval/audit_program_matcher_absorption.py` "
         f"({raw['generated_at']}, walk {raw['walk_seconds']}s).\n",
         "`match_programs` accepts the best candidate in a prefix group at ratio "
         f">= {_MATCH_THRESHOLD} and has no *reject* branch, so a program name absent "
         "from `programs.json` is absorbed by its nearest neighbour instead of "
         "matching nothing. This measures how far that reaches. **Nothing is "
         "changed here** -- the matcher is read by `build_gold_candidates.py` and "
         "`router.classify_query`, so a threshold move would move published "
         "numbers.\n",
         "## 1. Corpus\n",
         f"- files with >=1 program tag: **{raw['n_files_with_hits']:,}**",
         f"- accepted matches: **{len(hits):,}**",
         f"- span == canonical once the window's own {_WINDOW_SLACK}-char tail is "
         f"trimmed (clean): **{len(exact):,}** ({len(exact)/len(hits):.1%})",
         f"- span != canonical: **{len(inexact):,}** ({len(inexact)/len(hits):.1%})",
         f"- of those, >= {INSERT_FLOOR} inserted chars (a different name, not OCR "
         f"noise): **{len(suspicious):,}** ({len(suspicious)/len(hits):.1%} of all "
         "matches)\n",
         "Inserted-character distribution over the inexact spans -- the "
         f"{INSERT_FLOOR}-char cut is reported, not relied on:\n",
         "| inserted chars | matches |", "|---|---|"]
    for k in sorted(ins):
        L.append(f"| {k} | {ins[k]:,} |")

    L += ["\n## 2. Which canonicals absorb, and what\n",
          "Distinct spans absorbed per canonical, worst first. A canonical with "
          "one distinct span beyond itself is usually OCR; several distinct "
          "spans is the defect.\n",
          "| canonical | distinct absorbed spans | matches | example span |",
          "|---|---|---|---|"]
    per: dict[str, Counter] = defaultdict(Counter)
    for h in suspicious:
        per[h["canonical"]][h["trimmed"]] += 1
    for canonical, spans in sorted(per.items(), key=lambda kv: -len(kv[1]))[:20]:
        ex = max(spans, key=spans.get)
        L.append(f"| {canonical} | {len(spans)} | {sum(spans.values()):,} | `{ex}` |")
    L.append(f"\n{len(per)} of {len({h['canonical'] for h in hits})} matched canonicals "
             f"absorb at least one foreign span.\n")

    # The dominant shape, measured rather than eyeballed off the table above.
    # A degree-level swap is the worst kind of absorption to have: the two names
    # differ by one token, so the ratio stays far above threshold, and yet a
    # master's programme is tagged as the bachelor's of the same subject.
    levels = ("บัณฑิต", "มหาบัณฑิต", "ดุษฎีบัณฑิต")

    def level_of(s: str) -> str:
        for lv in ("ดุษฎีบัณฑิต", "มหาบัณฑิต", "บัณฑิต"):
            if lv in s:
                return lv
        return ""

    swapped = [h for h in suspicious
               if level_of(h["canonical"]) and level_of(h["trimmed"])
               and level_of(h["canonical"]) != level_of(h["trimmed"])]
    L.append(f"Of the {len(suspicious):,} absorbing matches, **{len(swapped):,}** "
             f"({len(swapped)/max(1, len(suspicious)):.1%}) swap the *degree level* "
             f"({'/'.join(levels)}) -- a one-token difference that keeps the ratio "
             "far above threshold while tagging, say, a master's programme as the "
             "bachelor's of the same subject. That is the shape to fix first if "
             "this is ever fixed.\n")
    return "\n".join(L), per, suspicious, hits


def impact(per, suspicious, hits) -> str:
    """§3-§4: does any of it reach the Gold set or the router?"""
    L = ["## 3. Does it reach the Gold set?\n"]
    # program_candidates() does NOT call match_programs: it takes the union of
    # files tagged by it and then gates on `canonical in resolution_id`, i.e.
    # an exact substring of the manifest TITLE. So an over-match can only add a
    # document whose own title literally names the program. Verified, not
    # assumed:
    gold = yaml.safe_load(GOLD.read_text(encoding="utf-8"))
    prog = [e for e in gold if e.get("entity_type") == "program"]
    bad = [(e["query"], rid) for e in prog for rid in e["relevant_resolution_ids"]
           if e["entity"] not in rid]
    L += [f"`program_candidates()` gates on `canonical in resolution_id` (an exact "
          f"substring of the manifest title), *after* seeding its pool from the "
          f"files `match_programs` tagged. So an absorption can only add a document "
          f"whose own title literally spells the program out.\n",
          f"- program gold queries: **{len(prog)}**",
          f"- gold pairs whose resolution_id does NOT literally contain the "
          f"program: **{len(bad)}**\n",
          "**So the absorption defect does not reach the program qrels.**"
          if not bad else f"**{len(bad)} pairs are not title-supported -- investigate.**",
          "\n## 4. Does it change a route?\n"]

    # classify_query only asks whether *any* program matched, so the failure
    # that would matter is a non-program query absorbed into the program route.
    counts = Counter()
    mism = []
    for e in gold:
        got = classify_query(e["query"])
        counts[(e.get("entity_type"), got)] += 1
        if e.get("entity_type") == "program" and got != "program":
            mism.append(e["query"])
    L += ["`classify_query` asks only whether *any* program matched, never which "
          "one, so an absorption changes a route only by turning a no-match into a "
          "match. Routes over the 106-query 73det set:\n",
          "| gold entity_type | route | queries |", "|---|---|---|"]
    for (et, route), n in sorted(counts.items()):
        L.append(f"| {et} | {route} | {n} |")
    L.append(f"\nA program query routed elsewhere: **{len(mism)}**. Every absorption "
             "found in §1 replaces one program name with another, and the route is "
             "the same either way -- so **the router is unaffected by construction**, "
             "not merely unaffected in this sample.\n")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--render", action="store_true",
                    help="re-derive the report from the cached walk")
    args = ap.parse_args()

    if args.render:
        raw = json.loads(RAW_PATH.read_text(encoding="utf-8"))
    else:
        raw = collect()
        RAW_PATH.parent.mkdir(parents=True, exist_ok=True)
        RAW_PATH.write_text(json.dumps(raw, ensure_ascii=False), encoding="utf-8")
        print(f"cached -> {RAW_PATH}")

    body, per, suspicious, hits = render(raw)
    text = body + "\n" + impact(per, suspicious, hits)

    checks = self_checks(raw)
    text += "\n## 5. Self-checks\n\n| check | result | detail |\n|---|---|---|\n"
    for name, ok, detail in checks:
        text += f"| {name} | {'PASS' if ok else 'FAIL'} | {detail} |\n"

    REPORT.write_text(text, encoding="utf-8")
    print(text)
    print(f"\nwritten -> {REPORT}")
    return 0 if all(ok for _, ok, _ in checks) else 1


if __name__ == "__main__":
    raise SystemExit(main())
