# An accepted span that differs from its canonical by this many *inserted*
# characters or more is reported separately from OCR noise. Not a verdict --
# the full distribution is printed so the cut is not load-bearing.
INSERT_FLOOR = 2


def match_programs_detailed(text: str, dictionary=None) -> list[dict]:
    """Both rules over one set of candidate ratios: one record per match the
    *pre-repair* matcher accepted, carrying the span and ratio it accepted it
    at, plus what the shipped degree-filtering matcher does with it.

      canonical -- the pre-repair winner. §1-§2 size the absorption defect from
                   this field, so those figures keep reproducing after the
                   repair; they are what motivated it.
      selected  -- what ships now: the same canonical, a re-selected one, or
                   None where the mention is left untagged.
      selected_span -- the span `selected` was accepted against, which is NOT
                   `span` for a rescue: the window is sized to each candidate's
                   own length. S7 needs this one; see the comment where it is set.
      bucket    -- why, for §3.

    Deliberately a transcription of both loops rather than a call into them --
    S1 gates `selected` against `match_programs` on real corpus text, because a
    measurement of a slightly different function measures nothing.
    """
    dictionary = dictionary if dictionary is not None else load_dictionary()
    grouped = _by_prefix(dictionary)
    pattern = _build_scan_pattern(tuple(grouped))
    out: list[dict] = []
    for m in pattern.finditer(text):
        scored = []
        for canonical in grouped[m.group(0)]:
            span = _bounded_span_for(text, m.start(), len(canonical))
            scored.append((SequenceMatcher(None, canonical, span).ratio(), canonical, span))
        qualified = [c for c in scored if c[0] >= _MATCH_THRESHOLD]
        if not qualified:
            continue
        best_ratio, best_canonical, best_span = max(qualified, key=lambda c: c[0])

        span_degree = degree_level(best_span)
        selected_span = best_span
        if span_degree is None or degree_level(best_canonical) in (None, span_degree):
            if _head_contradicted(best_canonical, best_span) or _subject_contradicted(
                best_canonical, best_span
            ):
                pick = next(
                    ((c, s) for _r, c, s in sorted(qualified, reverse=True)
                     if (span_degree is None or degree_level(c) in (None, span_degree))
                     and not _head_contradicted(c, s) and not _subject_contradicted(c, s)
                     and _field_agrees(c, s)),
                    None,
                )
                selected = pick[0] if pick else None
                if selected is not None:
                    selected_span = pick[1]  # per-candidate window, as above
                    bucket = "rescued (same degree, wrong programme)"
                else:
                    bucket = ("dropped: head noun contradicted"
                              if _head_contradicted(best_canonical, best_span)
                              else "dropped: subject contradicted")
            else:
                selected, bucket = best_canonical, "unchanged"
        else:
            same_level = [c for c in qualified if degree_level(c[1]) == span_degree]
            pick = next(
                ((c, s) for _r, c, s in sorted(same_level, reverse=True) if _field_agrees(c, s)),
                None,
            )
            selected = pick[0] if pick else None
            if selected is not None:
                # Record the span the rescue was tested against, NOT `best_span`.
                # `_bounded_span_for` sizes the window to each candidate's own
                # length, so a rescue onto a longer name reads further into the
                # text; judging it against the winner's shorter span cuts the
                # subject off and reports a contract violation that never
                # happened (S7 did exactly that on 4 of 354 -- all four cases
                # the dictionary's same-degree sibling is the longer name).
                selected_span = pick[1]
                bucket = "rescued"
            elif same_level:
                bucket = "dropped: same degree available, no subject agreed"
            elif _field_of(best_canonical) is None or _field_of(best_span) is None:
                bucket = "dropped: no subject to compare"
            else:
                bucket = "dropped: nothing at the span's own degree"
        out.append({"canonical": best_canonical, "span": best_span,
                    "ratio": round(best_ratio, 4),
                    "selected": selected, "selected_span": selected_span,
                    "bucket": bucket})
    return out


def strip_window_slack(canonical: str, span: str) -> str:
    """Drop the trailing characters the *window*, not the text, put there.

    `_bounded_span_for` reads `len(canonical) + _WINDOW_SLACK` characters, so an
    otherwise perfect span still ends in up to `_WINDOW_SLACK` characters of
    whatever followed the name -- `(กา`, ` จำน`, `(หล`. Counting those as
    inserted text is what the first run of this audit did, and it produced a
    headline of "99.3% of matches absorb a different name" whose mode sat
    exactly at 4 = `_WINDOW_SLACK`. The tail is trimmed to at most that many
    characters, so a genuinely longer name still registers the excess.

    Note what this cannot see: a name differing from its canonical only *after*
    the window ends is invisible to the matcher and therefore to this audit.
    That is a bound on the measurement, not a property of the corpus.
    """
    ops = SequenceMatcher(None, canonical, span).get_opcodes()
    last_equal = max((o for o in ops if o[0] == "equal"), key=lambda o: o[4],
                     default=None)
    if last_equal is None:
        return span
    tail = len(span) - last_equal[4]
    return span[: len(span) - min(tail, _WINDOW_SLACK)]


def inserted_chars(canonical: str, span: str) -> int:
    """Characters present in `span` but absent from `canonical`.

    The discriminator between "OCR misread a character" (a 1-char replace) and
    "this is a different program name" (a multi-char insert such as ทันต or
    พยาบาล). Counts the span side of both `insert` and `replace` opcodes, after
    `strip_window_slack` removes the window's own tail.
    """
    span = strip_window_slack(canonical, span)
    total = 0
    for tag, _i1, _i2, j1, j2 in SequenceMatcher(None, canonical, span).get_opcodes():
        if tag in ("insert", "replace"):
            total += j2 - j1
    return total


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return path.read_text(encoding="utf-8-sig")


def collect() -> dict:
    t0 = time.time()
    files: dict[str, list[dict]] = {}
    for i, path in enumerate(iter_corpus_files(CORPUS_ROOT)):
        text = strip_mapping_tables(strip_document_header(read_text(path)))
        hits = match_programs_detailed(text)
        if hits:
            files[str(path.relative_to(CORPUS_ROOT).as_posix())] = hits
        if i % 300 == 0:
            print(f"  ...{i} files, {time.time() - t0:.0f}s", flush=True)
    return {
        "generated_by": "tools/eval/audit_program_matcher_absorption.py",
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "walk_seconds": round(time.time() - t0, 1),
        "n_files_with_hits": len(files),
        "files": files,
    }


def self_checks(raw: dict) -> list[tuple[str, bool, str]]:
    checks: list[tuple[str, bool, str]] = []

    # S1 -- the instrumented matcher IS the shipped one. Sampled on real
    # corpus text, not a fixture: the transcription could diverge only on
    # inputs the fixture doesn't have. Gated on `selected`, the field that
    # tracks what ships; `canonical` deliberately no longer can be, since it
    # transcribes the rule the repair replaced.
    sample = [p for p in list(iter_corpus_files(CORPUS_ROOT))[::173]][:15]
    bad = []
    for path in sample:
        text = strip_mapping_tables(strip_document_header(read_text(path)))
        mine = sorted({h["selected"] for h in match_programs_detailed(text) if h["selected"]})
        if mine != match_programs(text):
            bad.append(path.name)
    checks.append(("S1 instrumented matcher == match_programs", not bad,
                   f"{len(sample)} files sampled, {len(bad)} differ"))

    # S2 -- every recorded span really does clear the shipped threshold, and
    # every recorded canonical really is in the dictionary.
    canon = {e["canonical"] for e in load_dictionary()}
    hits = [h for hs in raw["files"].values() for h in hs]
    ok = all(h["ratio"] >= _MATCH_THRESHOLD and h["canonical"] in canon for h in hits)
    checks.append(("S2 every recorded hit is dictionary-canonical and >= threshold",
                   ok, f"{len(hits):,} hits, threshold {_MATCH_THRESHOLD}"))

    # S3 -- an exact-span match must have zero insertions, or `inserted_chars`
    # is measuring the wrong thing and the whole §1 split is noise.
    exact = [h for h in hits if h["span"] == h["canonical"]]
    ok = all(inserted_chars(h["canonical"], h["span"]) == 0 for h in exact)
    checks.append(("S3 inserted_chars == 0 on every exact span", ok,
                   f"{len(exact):,} exact spans"))

    # S4 -- the known instance reproduces. If the two dental/nursing names
    # stopped being absorbed, this audit is about a defect that no longer
    # exists and the counts below would be silently measuring something else.
    target = "หลักสูตรแพทยศาสตรบัณฑิต"
    absorbed = {h["span"] for hs in raw["files"].values() for h in hs
                if h["canonical"] == target and h["span"] != target}
    ok = any("ทันต" in s for s in absorbed) or any("พยาบาล" in s for s in absorbed)
    checks.append(("S4 the motivating instance still reproduces", ok,
                   f"{len(absorbed)} distinct spans absorbed into {target}"))

    # S5 -- the check the first run of this audit did not have, and paid for.
    # `_bounded_span_for` reads len(canonical) + _WINDOW_SLACK characters, so a
    # perfect match still arrives with a tail; counting it made 6,807 matches
    # look like 4-char absorptions when 4 IS the slack. A span that is exactly
    # its canonical plus window tail must score zero, measured against the real
    # spans on disk rather than a fixture.
    slack_only = [h for h in hits
                  if h["span"] != h["canonical"]
                  and h["span"].startswith(h["canonical"])
                  and len(h["span"]) - len(h["canonical"]) <= _WINDOW_SLACK]
    ok = all(inserted_chars(h["canonical"], h["span"]) == 0 for h in slack_only)
    checks.append((f"S5 a pure {_WINDOW_SLACK}-char window tail counts as 0 inserted",
                   ok, f"{len(slack_only):,} slack-only spans"))

    # S6 -- the repair changed a match only through the stated mechanism. A
    # re-selection that is neither the old winner nor a same-degree candidate
    # would mean §3 is counting something other than the degree filter, and the
    # bucket names would be describing a rule the code no longer has.
    moved = [h for h in hits if h["selected"] not in (None, h["canonical"])]
    degree_moved = [h for h in moved if h["bucket"] == "rescued"]
    ok = all(degree_level(h["selected"]) == degree_level(h["span"])
             and degree_level(h["selected"]) != degree_level(h["canonical"])
             for h in degree_moved)
    checks.append(("S6 every degree re-selection sits at the span's own degree", ok,
                   f"{len(degree_moved):,} of {len(moved):,} re-selected by the degree filter"))

    # S7 -- and it is not a rename in disguise: a rescue must land on a
    # *different* canonical whose subject the text supports, which is the one
    # thing separating this from the degree-blind fallthrough that was measured
    # and rejected (11 re-tags, 3 correct). Judged against `selected_span`, the
    # window sized to the rescue's own length -- the first version of this check
    # used `span` (sized to the winner) and FAILED on 4 of 354, every one of
    # them the check truncating the subject it was about to compare.
    ok = all(_field_agrees(h["selected"], h["selected_span"]) for h in moved)
    checks.append(("S7 every re-selection agrees with the span's subject", ok,
                   f"{len(moved):,} matches re-selected"))

    # S8 -- how far a rescue may travel. A degree swap is the whole intent, so
    # the selected name should normally be the winner's subject at another
    # level; a rescue whose *subject* also moves is the dictionary holding a
    # longer sibling name, and it is reported rather than gated because the
    # corpus, not the rule, decides how many there are. It fails only if that
    # became the common case, which would mean the filter is re-ranking on
    # something other than degree.
    widened = [h for h in degree_moved if not _field_agrees(h["selected"], h["canonical"])]
    checks.append(("S8 a degree rescue keeps the winner's subject",
                   len(widened) <= max(1, len(degree_moved)) // 10,
                   f"{len(widened)} of {len(degree_moved):,} land on a longer sibling name"))

    # S9 -- the cross-subject half, gated on its own mechanism rather than on
    # the degree one. A same-degree rescue must NOT move the degree (that is
    # what the branch above is for) and must be uncontradicted on both halves,
    # which is the whole rule: this is the check that would fail if the guard
    # started re-selecting on the winner's ratio again.
    subject_moved = [h for h in moved if h["bucket"].startswith("rescued (same degree")]
    ok = all(
        degree_level(h["selected"]) == degree_level(h["canonical"])
        and not _head_contradicted(h["selected"], h["selected_span"])
        and not _subject_contradicted(h["selected"], h["selected_span"])
        for h in subject_moved
    )
    checks.append(("S9 every same-degree rescue keeps the degree and is uncontradicted",
                   ok, f"{len(subject_moved):,} matches rescued across subject"))

    # S10 -- a drop is exhaustive, not a first-candidate failure. Every match
    # left untagged by the cross-subject guard must have NO admissible
    # candidate at all, or the guard is dropping mentions whose right answer
    # was sitting in the dictionary -- exactly the error the degree half's
    # `reject` rule was rejected for (0 gained / 340 lost).
    dropped = [h for h in hits if h["bucket"].startswith("dropped: head")
               or h["bucket"].startswith("dropped: subject")]
    ok = all(_head_contradicted(h["canonical"], h["span"])
             or _subject_contradicted(h["canonical"], h["span"]) for h in dropped)
    checks.append(("S10 every cross-subject drop really is contradicted", ok,
                   f"{len(dropped):,} matches dropped by the cross-subject guard"))
    return checks


def render(raw: dict) -> str:
    hits = [h for hs in raw["files"].values() for h in hs]
    # Compare on the trimmed span throughout: the raw span always carries up to
    # `_WINDOW_SLACK` characters the window read past the name, so `span ==
    # canonical` would classify an otherwise-perfect match as a difference.
    for h in hits:
        h["trimmed"] = strip_window_slack(h["canonical"], h["span"])
    exact = [h for h in hits if h["trimmed"] == h["canonical"]]
    inexact = [h for h in hits if h["trimmed"] != h["canonical"]]
    ins = Counter(inserted_chars(h["canonical"], h["span"]) for h in inexact)
    suspicious = [h for h in inexact
                  if inserted_chars(h["canonical"], h["span"]) >= INSERT_FLOOR]

    L = [f"# `match_programs` absorption -- blast radius\n",
         f"Generated by `tools/eval/audit_program_matcher_absorption.py` "
         f"({raw['generated_at']}, walk {raw['walk_seconds']}s).\n",
         "`match_programs` used to accept the best candidate in a prefix group at "
         f"ratio >= {_MATCH_THRESHOLD} with no *reject* branch, so a program name "
         "absent from `programs.json` was absorbed by its nearest neighbour instead "
         "of matching nothing. **That is now repaired in two halves** (2026-08-11): a "
         "winner whose *degree level* the text contradicts no longer wins, and the "
         "degree instead *filters the candidate set* (§3); a winner whose *head noun "
         "or subject* the text contradicts at the same degree no longer wins either "
         "(§3b). §1-§2 below still size the original defect -- they are computed from "
         "the pre-repair winner, so the figures that motivated the fix keep "
         "reproducing. §4-§5 are why it was safe to ship: the matcher is read by "
         "`build_gold_candidates.py` and `router.classify_query`, and neither moves.\n",
         "## 1. Corpus\n",
         f"- files with >=1 program tag: **{raw['n_files_with_hits']:,}**",
         f"- accepted matches: **{len(hits):,}**",
         f"- span == canonical once the window's own {_WINDOW_SLACK}-char tail is "
         f"trimmed (clean): **{len(exact):,}** ({len(exact)/len(hits):.1%})",
         f"- span != canonical: **{len(inexact):,}** ({len(inexact)/len(hits):.1%})",
         f"- of those, >= {INSERT_FLOOR} inserted chars (a different name, not OCR "
         f"noise): **{len(suspicious):,}** ({len(suspicious)/len(hits):.1%} of all "
         "matches)\n",
         "Inserted-character distribution over the inexact spans -- the "
         f"{INSERT_FLOOR}-char cut is reported, not relied on:\n",
         "| inserted chars | matches |", "|---|---|"]
    for k in sorted(ins):
        L.append(f"| {k} | {ins[k]:,} |")

    L += ["\n## 2. Which canonicals absorb, and what\n",
          "Distinct spans absorbed per canonical, worst first. A canonical with "
          "one distinct span beyond itself is usually OCR; several distinct "
          "spans is the defect.\n",
          "| canonical | distinct absorbed spans | matches | example span |",
          "|---|---|---|---|"]
    per: dict[str, Counter] = defaultdict(Counter)
    for h in suspicious:
        per[h["canonical"]][h["trimmed"]] += 1
    for canonical, spans in sorted(per.items(), key=lambda kv: -len(kv[1]))[:20]:
        ex = max(spans, key=spans.get)
        L.append(f"| {canonical} | {len(spans)} | {sum(spans.values()):,} | `{ex}` |")
    L.append(f"\n{len(per)} of {len({h['canonical'] for h in hits})} matched canonicals "
             f"absorb at least one foreign span.\n")

    # The dominant shape, measured rather than eyeballed off the table above.
    # A degree-level swap is the worst kind of absorption to have: the two names
    # differ by one token, so the ratio stays far above threshold, and yet a
    # master's programme is tagged as the bachelor's of the same subject.
    levels = ("บัณฑิต", "มหาบัณฑิต", "ดุษฎีบัณฑิต")

    def level_of(s: str) -> str:
        for lv in ("ดุษฎีบัณฑิต", "มหาบัณฑิต", "บัณฑิต"):
            if lv in s:
                return lv
        return ""

    swapped = [h for h in suspicious
               if level_of(h["canonical"]) and level_of(h["trimmed"])
               and level_of(h["canonical"]) != level_of(h["trimmed"])]
    L.append(f"Of the {len(suspicious):,} absorbing matches, **{len(swapped):,}** "
             f"({len(swapped)/max(1, len(suspicious)):.1%}) swap the *degree level* "
             f"({'/'.join(levels)}) -- a one-token difference that keeps the ratio "
             "far above threshold while tagging, say, a master's programme as the "
             "bachelor's of the same subject. **That is the shape the repair in §3 "
             "attacks**, and it was picked because it is the largest one here.\n")
    return "\n".join(L), per, suspicious, hits


def _cut_distribution(hits: list[dict]) -> str:
    """The sentence defending §3b's two thresholds, RECOMPUTED from the cache.

    It was hardcoded prose until 2026-08-11, and by the second walk every figure
    in it was wrong -- it had been measured once, in a probe, over a population
    nobody wrote down. Counts are not p-values, so nothing downstream verdicts
    on them; that is exactly why a typed one rots unnoticed
    ([[feedback_verify_status_numbers_against_the_artifact]]). The population is
    now stated in the sentence itself: matches where *both* sides carry the half
    being measured, which is the only set either test ever runs on.
    """
    head, subj = [], []
    for h in hits:
        a, b = _head_of(h["canonical"]), _head_of(h["span"])
        if a and b:
            head.append(SequenceMatcher(None, a, b).ratio())
        a, b = _field_of(h["canonical"]), _field_of(h["span"])
        if a and b:
            shared = SequenceMatcher(None, a, b).find_longest_match(
                0, len(a), 0, len(b)).size
            subj.append(shared / min(len(a), len(b)))

    def band(v, lo, hi):
        return sum(1 for x in v if lo <= x < hi)

    return (
        "Neither cut is load-bearing, and the distribution says so rather than "
        "the choice being defended on taste. Over the matches where both sides "
        f"carry a head noun (**{len(head):,}**), head ratio sits at exactly 1.00 "
        f"for **{band(head, 1.0, 1.01):,}** and only "
        f"**{band(head, _HEAD_THRESHOLD - 0.05, _HEAD_THRESHOLD):,}** land in the "
        f"band immediately below the {_HEAD_THRESHOLD:.2f} cut, against "
        f"**{band(head, _HEAD_THRESHOLD, _HEAD_THRESHOLD + 0.05):,}** immediately "
        "above it -- so the cut separates a dense mass of agreement from a thin "
        "tail, it does not slice through the middle of one. Subject coverage, "
        f"over the **{len(subj):,}** matches where both sides carry a `สาขาวิชา`, "
        f"is the same shape: **{band(subj, 1.0, 1.01):,}** at 1.00, "
        f"**{band(subj, 0.70, 0.80):,}** between 0.70 and 0.80 and "
        f"**{band(subj, 0.80, 0.85):,}** between 0.80 and 0.85. And a subject drop "
        "no longer turns on that cut alone -- it needs the ratio test against it "
        "too, which is what rule (1) above added.\n")


def repair(raw: dict, hits: list[dict]) -> str:
    """§3: what the degree filter does, and what the two rejected rules did.

    Three rules were walked over this corpus before one shipped, and the two
    that lost were rejected by their own numbers rather than on taste. Their
    counts are kept here because a fix that only reports its own arm cannot
    show that it beat anything.
    """
    buckets = Counter(h["bucket"] for h in hits)
    subject_buckets = [b for b in buckets if b.startswith("rescued (same degree")
                       or b.startswith("dropped: head") or b.startswith("dropped: subject")]
    fired = sum(n for b, n in buckets.items()
                if b != "unchanged" and b not in subject_buckets)
    rescued = buckets["rescued"]
    widened = [h for h in hits if h["bucket"] == "rescued"
               and not _field_agrees(h["selected"], h["canonical"])]

    # File-level, because a tag is per file: a mention dropped in a file that
    # names the same programme elsewhere costs nothing. Both guards are counted
    # separately as well as together -- the degree half's published figures were
    # measured before the cross-subject half existed, and a combined-only table
    # would silently move them.
    def per_file(selector) -> tuple[int, int, int, int]:
        gained = lost = stripped = changed = 0
        for hs in raw["files"].values():
            old = {h["canonical"] for h in hs}
            new = {s for h in hs if (s := selector(h))}
            if old != new:
                changed += 1
                gained += len(new - old)
                lost += len(old - new)
            if old and not new:
                stripped += 1
        return gained, lost, stripped, changed

    # Degree-only counterfactual: a hit the cross-subject guard touched keeps
    # the pre-repair winner, which is exactly what the degree half did to it.
    degree_only = per_file(
        lambda h: h["canonical"] if h["bucket"] in subject_buckets else h["selected"])
    both = per_file(lambda h: h["selected"])
    gained, lost, stripped, changed = degree_only

    L = ["\n## 3. The repair, and the two rules it beat\n",
         f"The degree guard fires on **{fired:,}** of the {len(hits):,} accepted "
         "matches -- every one a mention whose text names a degree its winner "
         "contradicts. What should happen there was measured, not argued:\n",
         "| outcome | matches | |", "|---|---|---|"]
    order = ["rescued",
             "dropped: same degree available, no subject agreed",
             "dropped: no subject to compare",
             "dropped: nothing at the span's own degree"]
    why = {
        "rescued": "a same-degree candidate whose subject the span supports was "
                   "already in the dictionary -- the matcher had not run out of "
                   "options, it had ranked them wrong",
        "dropped: same degree available, no subject agreed":
            "the ...ดุษฎีบัณฑิต ...ไฟฟ้า family: filtering on degree alone would hand "
            "these to ...โยธา, trading a wrong degree for a wrong subject",
        "dropped: no subject to compare":
            "undecidable, not wrong -- one side has no `สาขาวิชา`, so no evidence "
            "means no rescue",
        "dropped: nothing at the span's own degree":
            "nothing in the dictionary fits, so *matches nothing* is the right answer",
    }
    for b in order:
        L.append(f"| {b} | **{buckets[b]:,}** | {why[b]} |")

    L += [f"\n**{rescued:,} of {fired:,} ({rescued/max(1, fired):.0%}) were "
          "recoverable**, which is what decides between the two candidate rules. A "
          "plain *reject* -- drop the mention whenever the degree contradicts -- "
          "throws all of those away; the degree filter keeps them, and removes "
          "exactly the same mentions otherwise. So reject is dominated, not merely "
          "beaten on a preference.\n",
          "Per file, against the pre-repair matcher:\n",
          "| | tags gained | tags lost | files losing every tag | files changed |",
          "|---|---|---|---|---|",
          f"| degree guard alone | **{gained:,}** | {lost:,} | "
          f"**{stripped:,}** | {changed:,} |",
          f"| shipped (both guards) | **{both[0]:,}** | {both[1]:,} | "
          f"**{both[2]:,}** | {both[3]:,} |\n",
          "The earlier fallthrough rule, walked the same way, re-tagged 11 mentions "
          "of which 3 were the right programme -- eliminating the winner in a prefix "
          "group leaves candidates that are by construction *different programmes*, "
          "so the subject test is what makes a re-selection safe.\n",
          f"How far a rescue travels: **{len(widened)} of {rescued:,}** land on a name "
          "whose subject is *longer* than the winner's rather than the same subject at "
          "another level (`...การจัดการโลจิสติกส์` -> "
          "`...การจัดการโลจิสติกส์และซัพพลายเชน`). The window is sized to each "
          "candidate's own length, so those rescues read further into the text and "
          "were judged on what they read -- the first version of S7 judged them "
          "against the *winner's* shorter span, cut the subject in half, and reported "
          "4 contract violations that had not happened.\n"]

    # --- 3b: the half the degree filter is structurally unable to see --------
    sub_fired = sum(buckets[b] for b in subject_buckets)
    sub_rescued = buckets["rescued (same degree, wrong programme)"]
    head_drop = buckets["dropped: head noun contradicted"]
    subj_drop = buckets["dropped: subject contradicted"]
    L += ["\n## 3b. The same-degree half (2026-08-11)\n",
          "`หลักสูตรทันตแพทยศาสตรบัณฑิต` and `หลักสูตรพยาบาลศาสตรบัณฑิต` are both "
          "absorbed by `หลักสูตรแพทยศาสตรบัณฑิต` at the *same* degree, so the filter "
          "above never fires on them -- they are the motivating instance of this whole "
          "audit (§S4) and the degree repair could not reach them. The mechanism is "
          "**dilution by concatenation**: the ratio is computed over head noun + "
          "subject joined, so a disagreement confined to one half is averaged away by "
          "the other half agreeing (`ทันต-` scores 0.88). Testing the two halves "
          "*separately* removes the dilution.\n",
          "The two halves need **different** tests, and the asymmetry is structural "
          "rather than a fudge: `_bounded_span_for` sizes the window from the match "
          "position, so the head noun (immediately after the `หลักสูตร` anchor) is "
          "always covered in full, while the subject sits at the tail and is routinely "
          "truncated. So truncation must be *forgiven* in the subject "
          "(longest-common-substring coverage, where a cut name still scores 1.00) and "
          "must **not** be forgiven in the head (extra leading material is a different "
          "formal degree name). Both tests are positive-evidence-only: no `สาขาวิชา` "
          "on either side is not a contradiction.\n",
          f"| outcome | matches | |", "|---|---|---|",
          f"| rescued (same degree, wrong programme) | **{sub_rescued:,}** | a "
          "candidate the text contradicts on neither half was already in the "
          "dictionary |",
          f"| dropped: head noun contradicted | **{head_drop:,}** | ทันต-/พยาบาล-/"
          "วิทยาศาสตร- against แพทยศาสตร-: a different degree name, not a different "
          "level |",
          f"| dropped: subject contradicted | **{subj_drop:,}** | same head noun, a "
          "`สาขาวิชา` the winner's does not cover |",
          f"\nThe guard fires on **{sub_fired:,}** of {len(hits):,} accepted matches, "
          f"and unlike the degree half it is mostly **drops** ({sub_rescued:,} "
          f"rescued, {head_drop + subj_drop:,} dropped) -- which is itself the "
          "finding: where a degree swap usually has the right answer sitting one level "
          "away in the dictionary, a cross-subject absorption usually does not, "
          "because the absorbed programme is simply **not in `programs.json`**. "
          "*Matches nothing* is the correct answer there, and until now it was not an "
          "available one.\n",
          "Two rules were added after the first walk, both because a self-check went "
          "red rather than because anything was reasoned out in advance -- the "
          "corpus was fine and the guard was wrong, twice. (1) **A drop needs both "
          "subject tests against it.** Coverage is blind to a difference spread "
          "through the string rather than sitting at one end, so a one-character "
          "dictionary/OCR variant (`วิศวกรรมเล็กทรอนิกส์` against "
          "`วิศวกรรมอิเล็กทรอนิกส์`) covers 0.55 while `_field_agrees` -- this "
          "project's own settled test for the very same relation -- puts it at 0.95. "
          "One pair must not be agreeing and contradicting at once, so the guard "
          "convicts only when coverage **and** ratio are both against it; **133 of "
          "569** subject drops sat in exactly that band. (2) **A cross-subject rescue "
          "may not cross the degree.** This branch is reached precisely when the "
          "*winner's* degree is uncontradicted, which says nothing about the "
          "runner-up's -- 6 rescues in the first walk moved a mention between "
          "บัณฑิต and มหาบัณฑิต, silently undoing §3's rule (S9).\n",
          _cut_distribution(hits)]
    return "\n".join(L)


def impact(per, suspicious, hits) -> str:
    """§4-§5: does any of it reach the Gold set or the router?"""
    L = ["## 4. Does it reach the Gold set?\n"]
    # program_candidates() does NOT call match_programs, and it does not read
    # the tags either: it iterates the mapping's KEYS, and tag_programs.py
    # writes a key for every live corpus file including the zero-match ones. So
    # the pool is the corpus, the tag VALUES are never read, and the only gate
    # is `canonical in resolution_id` -- an exact substring of the manifest
    # TITLE. An over-match therefore cannot reach the qrels at all; only corpus
    # *membership* can. Executed (not argued) by S2 in
    # tools/corpus_prep/audit_program_tag_regeneration.py, which blanks every
    # value and requires identical output. The gold-pair check below stays as
    # the independent second route:
    gold = yaml.safe_load(GOLD.read_text(encoding="utf-8"))
    prog = [e for e in gold if e.get("entity_type") == "program"]
    bad = [(e["query"], rid) for e in prog for rid in e["relevant_resolution_ids"]
           if e["entity"] not in rid]
    L += [f"`program_candidates()` iterates `programs_by_file.json`'s **keys**, and "
          f"`tag_programs.py` writes a key for every live corpus file -- including "
          f"the ones matching zero programs. So the tag *values* are never read: "
          f"the pool is the corpus, and the only gate is `canonical in "
          f"resolution_id`, an exact substring of the manifest title. An absorption "
          f"therefore cannot reach the program qrels **structurally**, not merely in "
          f"this sample -- executed by S2 in "
          f"`tools/corpus_prep/audit_program_tag_regeneration.py`, which blanks every "
          f"value and requires identical output. Only corpus *membership* can move "
          f"them. Second, independent route:\n",
          f"- program gold queries: **{len(prog)}**",
          f"- gold pairs whose resolution_id does NOT literally contain the "
          f"program: **{len(bad)}**\n",
          "**So the absorption defect does not reach the program qrels.**"
          if not bad else f"**{len(bad)} pairs are not title-supported -- investigate.**",
          "\n## 5. Does it change a route?\n"]

    # classify_query only asks whether *any* program matched, so the failure
    # that would matter is a non-program query absorbed into the program route.
    counts = Counter()
    mism = []
    for e in gold:
        got = classify_query(e["query"])
        counts[(e.get("entity_type"), got)] += 1
        if e.get("entity_type") == "program" and got != "program":
            mism.append(e["query"])
    L += ["`classify_query` asks only whether *any* program matched, never which "
          "one, so an absorption changes a route only by turning a no-match into a "
          "match. Routes over the 106-query 73det set:\n",
          "| gold entity_type | route | queries |", "|---|---|---|"]
    for (et, route), n in sorted(counts.items()):
        L.append(f"| {et} | {route} | {n} |")
    L.append(f"\nA program query routed elsewhere: **{len(mism)}**. Every absorption "
             "found in §1 replaces one program name with another, and the route is "
             "the same either way -- so **the router is unaffected by construction**, "
             "not merely unaffected in this sample.\n")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--render", action="store_true",
                    help="re-derive the report from the cached walk")
    args = ap.parse_args()

    if args.render:
        raw = json.loads(RAW_PATH.read_text(encoding="utf-8"))
        # A cache written before the 2026-08-11 repair has no `selected`, and
        # §3 would then be reporting the absence of a field as the absence of a
        # re-selection ([[feedback_undefined_is_not_zero]]). Refuse instead.
        if any(k not in h for hs in raw["files"].values() for h in hs
               for k in ("selected", "selected_span")):
            print(f"{RAW_PATH.name} predates the degree-filter repair "
                  "(no `selected`/`selected_span` field) -- re-run without --render.")
            return 1
    else:
        raw = collect()
        RAW_PATH.parent.mkdir(parents=True, exist_ok=True)
        RAW_PATH.write_text(json.dumps(raw, ensure_ascii=False), encoding="utf-8")
        print(f"cached -> {RAW_PATH}")

    body, per, suspicious, hits = render(raw)
    text = body + "\n" + repair(raw, hits) + "\n" + impact(per, suspicious, hits)

    checks = self_checks(raw)
    text += "\n## 6. Self-checks\n\n| check | result | detail |\n|---|---|---|\n"
    for name, ok, detail in checks:
        text += f"| {name} | {'PASS' if ok else 'FAIL'} | {detail} |\n"

    REPORT.write_text(text, encoding="utf-8")
    print(text)
    print(f"\nwritten -> {REPORT}")
    return 0 if all(ok for _, ok, _ in checks) else 1


if __name__ == "__main__":
    # The report is Thai and uses `§`; a Windows console defaults to cp874 and
    # would crash on the echo *after* the file is already written, turning a
    # clean run into a traceback and losing the self-check exit code.
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
