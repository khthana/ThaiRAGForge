"""How much does `match_programs` absorb names that are not in its dictionary?

Found as a side effect of building the relation graph (2026-08-10): edge A's
whole `ambiguous` row for `หลักสูตรแพทยศาสตรบัณฑิต` turned out to be
`หลักสูตรทันตแพทยศาสตรบัณฑิต` and `หลักสูตรพยาบาลศาสตรบัณฑิต` -- two real,
different programs -- both matching it. `match_programs` has no "matches
nothing" exit for a near miss: it keeps the best candidate in the prefix group
and accepts it at ratio >= 0.82, so a corpus name absent from `programs.json`
is absorbed by its nearest dictionary neighbour rather than rejected.

The first run of this script measured the blast radius and deliberately fixed
nothing: the matcher is read by `build_gold_candidates.py` and by
`router.classify_query`, so moving the threshold would move published numbers,
which is precisely why the size had to be known first. Scope was already bounded
on one side: 0 of the 253 dictionary names collide with *each other* at
threshold, so every absorption is a collision with a name outside the dictionary.

**The repair landed 2026-08-11 in two halves and this script measures both.**
Neither is a threshold move. (§3) 35.7% of absorptions swap only the *degree*
level, so a winner whose degree the text contradicts is replaced by the best
same-degree candidate whose subject the span also supports. (§3b) The rest swap
the *programme* at the same degree -- the ทันต-/พยาบาล- -> แพทย- shape the first
half is structurally unable to see -- so the head noun and the subject are
compared separately, which is what removes the dilution the joined ratio suffers
from. Either way the mention goes untagged when nothing fits. §1-§2 are computed
from the pre-repair winner so the figures that motivated the fix keep
reproducing; §3/§3b measure each repair against them.

Four questions, in the order that decides whether a fix is worth anything:

  1. CORPUS   how many accepted matches have a span that is not the canonical,
              and how many of those inserted enough text to be a different
              program rather than OCR noise;
  2. SHAPE    which canonicals absorb what, and what the dominant shape is;
  3. REPAIR   what the degree filter recovers, what it drops, and what the two
              rejected candidate rules would have done instead;
  4. QRELS
     + ROUTER whether any of it -- defect or repair -- reaches the Gold set or
              changes a route.

Run (CPU only, one corpus walk ~5 min):
    PYTHONPATH=src python tools/eval/audit_program_matcher_absorption.py
    ... --render     # re-derive the report from the cached walk, no walk

Generated by tools/eval/audit_program_matcher_absorption.py
"""
