"""The docs layer of the invariant sweep: check what the prose *says* against
what the artifacts on disk actually hold.

`audit_pipeline_invariants.py` gates three layers (C = corpus, I = index,
E = eval) and `diff_significance_reports.py` gates report-vs-report. Nothing
gated report-vs-**prose**, and that is where this project's avoidable mistakes
have actually happened: a number written by hand into `CLAUDE.md` or
`docs/paper-results-summary.md`, correct on the day it was typed, that no
later refresh touches because a refresh re-runs scripts and diffs reports --
it never reads the prose.

The failure is invisible to every existing guard by construction. The case that
motivated this script: the per-chunker BM25-vs-embedder table in
`paper-results-summary.md` drifted from its report in the 2026-08-06 refresh
(`e5` reads +0.0675/+0.1188/+0.1017/+0.1223, the report says
+0.0674/+0.1161/+0.1036/+0.1233). Every *verdict* cell was identical, so
`diff_significance_reports.py` correctly reported 0 flips and nobody re-copied
the numbers.

Checks (D = docs):

    D1  a report older than the script that generates it (prose quoting it is
        quoting a stale run), plus reports whose generator can't be identified
    D2  a number in the prose that appears in no report -- the main check
    D3  a significant p-value (<0.05) quoted inside a sentence that calls the
        result not significant, or vice versa
    D4  an eval *input* (a constant a script reads) changed after the report
        that depends on it was generated -- the "editing ROUTE_COMBO silently
        re-scores soft_vs_hard_routing.md" failure
    D5  a count/total figure ("N of M", "N จาก M") that no report states as a
        pair -- the class D2 is structurally blind to, since it matches only
        4-decimal figures
    D7  a unit-suffixed figure ("2,058.9 ms", "9.81 q/s") that no report
        states -- the other class D2 cannot see, and the one that let a whole
        serving layer's latencies drift. Covers PYTHON DOCSTRINGS as well as the
        docs, since a docstring is prose too and was outside every check here
        until 2026-08-23
    D8  a NAMED QUANTITY quoted at a value it no longer has -- the quantity->value
        map D2 is not, with the superseded values derived by diffing each report
        against its own `_*/` snapshots. The one check here that can see rot D2's
        own haystack shares

Design rules, each learned by getting one of these checks wrong.

  * A HAYSTACK THAT IS TOO BIG STOPS BEING A CHECK. D2 scans `data/results/**/*.md`
    only. Including the per-query JSON makes it vacuous rather than thorough: 225
    MB of scores contains almost any 4-decimal value by coincidence, which took
    the untraceable count 122 -> 27 without one of those 95 being genuinely
    sourced.
  * SCORE A CANDIDATE RULE AGAINST ITS OWN PERTURBATIONS. D5 matches count/total
    figures, where coincidental collision is far likelier than for 4-decimal ones,
    so every candidate rule was re-tested with each observed pair moved to n+1,
    m+1 and n+7 -- a rule that clears a wrong number as readily as a right one is
    not a check:

        rule                                real   n+1   m+1   n+7
        V1  the pair stated in the same shape  64%   13%    4%    4%
        V2  both integers on one line          89%   59%   39%   33%
        V3  both integers in one file          93%   80%   68%   71%
        proximity (<= 40 chars apart)          85%   47%   33%   40%

    Only V1 is a check. V1's 64% also means ~36% of *correct* figures are
    untraceable by construction, which is why D5 WARNs rather than FAILs.
  * AN EXEMPTION IS ONLY EVER RIGHT FOR THE CHECK IT WAS CALIBRATED ON. Inheriting
    D2's DATED exemption into D5 cleared 18 of its 26 flags INCLUDING the one true
    positive, because CLAUDE.md dates nearly every bullet. Both directions are
    pinned in tests. Entries in the `counts:` section are keyed on the exact figure
    string and each names the report line supporting it, so changing either half
    re-flags rather than staying silently cleared.
  * PROVENANCE BELONGS IN THE GENERATOR. D1b closed 18 -> 0 by having each emitting
    script write its own "Generated by" line; a hand-added line is erased by the
    next run. That edit moves the script's mtime, which is what D1a watches, so the
    cheap generators were RE-RUN rather than hand-patched. D1c then warns if a
    RETIRED_REPORTS entry names a missing file, because an exemption list is the
    easiest way to make a check vacuous -- the same rule D6 applies to the
    allowlist, and `report_currency.py` imports RETIRED_REPORTS rather than
    re-listing it.
  * DISCHARGE A D4 FLAG BY RE-RUNNING, NOT BY ALLOWLISTING. D4 is a staleness
    proxy; when the re-run is cheap it is also the definitive answer, and it has
    come back byte-identical every time it has fired here. The `inputs` section
    takes an optional `src_sha` so an exemption survives only while the source
    still hashes to it -- a pair-keyed exemption would disarm the very edge that
    was added because a matcher repair moved a report twice without touching its
    generator. An exemption's strongest state is not existing.
  * D2 IS A BAG OF NUMBERS, NOT A QUANTITY->VALUE MAP, and no filter over that
    haystack fixes it. FIVE candidate "the docs disagree" checks were built and ALL
    FIVE refuted -- do not re-propose them: (a) filter D2's haystack by report
    currency (a fresh report legitimately quotes registered, anchored and
    superseded values, so it cleared both real cases); (b) cross-layer
    near-neighbour matching (1,740 candidate pairs at the required epsilon, the
    closest hits pure coincidence); (c) citation-scoped traceability (under a tenth
    of blocks covered, residue all false positives); (d) D2/D5 themselves, already
    clean; (e) excluding superseded backup copies from the haystack (54 of 139
    reports are such copies, and excluding them costs 103 residue). The working
    method is instead: re-run the report, then sweep the prose, plus the standing
    convention -- date the claim.
  * D3 IS A WARN BY DESIGN. Its false positives are irreducible: a parenthetical
    can attribute its p-value to one arm and its verdict word to another.
  * MTIMES, NOT GIT DATES. Reports are gitignored and a script's commit lands after
    the run, which flagged all 10 D1 pairs as false positives on the first run.

Read-only. Exits 1 if any check FAILs.

Run:
    python tools/eval/audit_doc_claims.py
    python tools/eval/audit_doc_claims.py --list        # every D2/D5 hit, with context
    python tools/eval/audit_doc_claims.py --report docs/doc-claims-audit.md
"""
