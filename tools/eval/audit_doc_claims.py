SOURCE_GLOBS = ["src/rag_lab/**/*.py", "tools/**/*.py", "app/**/*.py", "tests/**/*.py"]


def _source_docstrings() -> list[tuple[str, str]]:
    """(relative path, docstring) for every module/class/function docstring."""
    out: list[tuple[str, str]] = []
    for g in SOURCE_GLOBS:
        for p in sorted(REPO.glob(g)):
            try:
                tree = ast.parse(p.read_text(encoding="utf-8"))
            except (SyntaxError, UnicodeDecodeError):
                continue
            rel = str(p.relative_to(REPO)).replace(chr(92), "/")
            for node in ast.walk(tree):
                if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                                     ast.AsyncFunctionDef)):
                    d = ast.get_docstring(node)
                    if d:
                        out.append((rel, d))
    return out


def _table_values(text: str, section: str | None, rows: list[str],
                  ncols: int | None = None) -> set[float]:
    """Every 4-decimal figure on every matching table row.

    The WHOLE row, not just its first cell: a significance row carries a
    baseline, a treatment, an effect size and a CI, and the prose quotes all of
    them. Reading only the first would leave `0.7730 -> 0.6940` half-watched, and
    the half it dropped is the one that moves. Taking everything also widens
    `current`, which is the conservative direction -- a block quoting ANY live
    value of the quantity passes.
    """
    if section:
        i = text.find(section)
        if i < 0:
            return set()
        rest = text[i + len(section):]
        j = re.search(r"^## ", rest, re.M)
        text = rest[: j.start()] if j else rest
    out: set[float] = set()
    pats = [re.compile(r) for r in rows]
    for ln in text.splitlines():
        if any(p.search(ln) for p in pats):
            # A CI is not the quantity. Its endpoints are arbitrary 4-decimals
            # that collide with unrelated effect sizes all over the corpus of
            # prose -- the first widened run flagged CLAUDE.md's `weighted x
            # fetch_depth` -0.0609 against a RETIRED CI bound of the alpha
            # sweep, two unrelated experiments. Stripping brackets removed every
            # such false positive without losing a figure the prose quotes.
            out.update(float(x) for x in NUM.findall(re.sub(r"\[[^\]]*\]", "", ln))[:ncols])
    return out


def _quantity_values(report: str, section: str | None, rows: list[str],
                     ncols: int | None = None) -> tuple[set[float], set[float]]:
    """(current, superseded) -- superseded derived from the `_*/` snapshots."""
    live = RESULTS / report
    if not live.exists():
        return set(), set()
    cur = _table_values(live.read_text(encoding="utf-8", errors="ignore"), section,
                        rows, ncols)
    old: set[float] = set()
    for snap in RESULTS.glob("_*/" + report):
        old |= _table_values(snap.read_text(encoding="utf-8", errors="ignore"),
                             section, rows, ncols)
    return cur, old - cur


def _prose_blocks(text: str) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    cur: list[str] = []
    start = line = 1
    for ln in text.splitlines():
        if (not ln.strip() or QUANTITY_BLOCK.match(ln)) and cur:
            out.append((start, "\n".join(cur)))
            cur = []
            start = line
        if ln.strip():
            if not cur:
                start = line
            cur.append(ln)
        line += 1
    if cur:
        out.append((start, "\n".join(cur)))
    return out


def audit_quantities(show_all: bool) -> None:
    """D8: a named quantity quoted at a value it no longer has.

    FAILs rather than WARNs, unlike D2/D5/D7. Those ask whether a figure is
    *traceable*, a question with irreducible false positives; this one asks
    whether it is *this quantity's current value*, and a superseded value beside
    a live label is wrong by construction. Its perturbation clearance is 0 for
    the same reason -- there is one right answer, not a bag to collide with.

    Its first run found 12 stale claims across four documents that D2 passed,
    including three present-tense "S2 reproduces X" anchor sentences and a whole
    superseded arm table in `paper-results-summary.md`. The one class it must not
    flag is a FROZEN PRE-REGISTRATION, where a figure that no longer matches is
    the point of having written it down; those are allowlisted by (doc, quantity)
    with the reason stated, and D6 audits them like every other exemption.

    A quantity whose report or table cannot be read is reported UNRESOLVED rather
    than passing silently -- renaming a row label is exactly how this check would
    otherwise go quietly vacuous.
    """
    allow = {(e["doc"], str(e["quantity"])) for e in _allowlist("quantities")}
    flagged: list[tuple[str, int, str, list[float], list[float]]] = []
    watched = 0
    unresolved: list[str] = []

    for name, report, section, rows, labels, *rest in WATCHED_QUANTITIES:
        ncols = rest[0] if rest else None
        cur, old = _quantity_values(report, section, rows, ncols)
        if not cur:
            unresolved.append(f"{name} ({report})")
            continue
        watched += 1
        if not old:
            continue
        for doc in DOCS:
            p = REPO / doc
            if not p.exists():
                continue
            rel = str(doc).replace(chr(92), "/")
            if (rel, name) in allow:
                continue
            for start, blk in _prose_blocks(_unemph(p.read_text(encoding="utf-8"))):
                if not any(l in blk for l in labels):
                    continue
                figs = {float(x) for x in NUM.findall(blk)}
                stale = figs & old
                if stale and not (figs & cur):
                    flagged.append((rel, start, name, sorted(stale), sorted(cur)))

    detail = (f"{len(flagged)} blocks quote a superseded value of {watched} watched "
              f"quantities across {len(DOCS)} docs")
    if unresolved:
        detail += (f"; UNRESOLVED: {', '.join(unresolved)} -- "
                   f"the cross-check could not be made")
    record("D8 a named quantity is quoted at its current value", not flagged, detail)
    for rel, start, name, stale, cur in (flagged if show_all else flagged[:12]):
        print(f"        {rel}:{start}  {name}: quotes {stale}, current {cur}")
    if not show_all and len(flagged) > 12:
        print(f"        ... {len(flagged) - 12} more (--list)")


def record(check: str, ok: bool, detail: str, warn: bool = False) -> None:
    status = "PASS" if ok else ("WARN" if warn else "FAIL")
    findings.append((check, status, detail))
    print(f"[{status}] {check}: {detail}")


def _mtime(p: Path) -> datetime:
    """Filesystem mtime, same convention as `audit_pipeline_invariants.py`'s I6/E4.

    Deliberately *not* the git commit date, which is wrong here in both
    directions: `data/results/` is gitignored so a report has no commit date at
    all, and a script's commit lands *after* the run that produced the report
    (generate, read, then commit both) -- so taking the later of the two flagged
    all 10 report/script pairs on this script's first run, every one a false
    positive. The cost is that a fresh clone rewrites every mtime to checkout
    time and D1a/D4 go quiet; that is already true of the checks this mirrors.
    """
    return datetime.fromtimestamp(p.stat().st_mtime, timezone.utc)


def _int(s: str) -> int:
    """"23,156" and "23156" are the same count; the prose and the reports differ
    on the separator freely, so compare the values, not the strings."""
    return int(s.replace(",", ""))


def _blocks(lines: list[str]) -> list[list[tuple[int, str]]]:
    """Split into contiguous non-blank runs (a paragraph or a markdown table)."""
    out: list[list[tuple[int, str]]] = []
    cur: list[tuple[int, str]] = []
    for i, ln in enumerate(lines):
        if ln.strip():
            cur.append((i + 1, ln))
        elif cur:
            out.append(cur)
            cur = []
    if cur:
        out.append(cur)
    return out


def _allowlist(section: str) -> list[dict]:
    """Triaged exemptions, each carrying the reason it was cleared.

    A reason field rather than a bare list on purpose: an exemption whose
    justification is not written down is indistinguishable from a check that was
    switched off, and the next person cannot re-audit it.
    """
    if not ALLOWLIST.exists():
        return []
    raw = yaml.safe_load(ALLOWLIST.read_text(encoding="utf-8")) or {}
    return raw.get(section) or []


