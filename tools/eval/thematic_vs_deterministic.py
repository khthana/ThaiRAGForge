"""Compare the two gold query shapes on identical combos: thematic vs entity-anchored.

The 252-entry set has been described since 2026-07-17 as *diluting* results with
"near-zero discriminative power" thematic queries. Now that all 179 name their
meeting (`qualify_thematic_queries.py`) and have been re-retrieved
(`run_thematic_eval.py`), that description is testable -- and this script exists
because the answer changes it: the thematic queries do not carry *no* signal, they
carry signal that points the **other way** on the chunker axis. Averaging the two
sets together cancels a real effect rather than adding noise to a real one.

Both sides use the same 36 `chunker_compare_full` combos, the same dense
retrieval, the same recall@10, so nothing but the query shape differs.

Run:
    PYTHONPATH=src python tools/eval/thematic_vs_deterministic.py
"""
from __future__ import annotations

import statistics
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import yaml

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from rag_lab.metrics import recall_at_k  # noqa: E402
from rag_lab.results import load_retrieval_result  # noqa: E402

from embedder_matrix_9way import EMBEDDER_ORDER, build_combo_to_chunker_embedder  # noqa: E402

K = 10
OUT = REPO / "data" / "results" / "thematic_vs_deterministic.md"
SETS = [
    ("thematic (179, meeting-qualified)",
     REPO / "data" / "results" / "thematic_dense",
     REPO / "config" / "eval" / "gold_query_set.yaml", True),
    ("entity-anchored (106, 73-det)",
     REPO / "data" / "results" / "gold_73det_full_embedder_matrix",
     REPO / "config" / "eval" / "gold_query_set_73det.yaml", None),
]


def measure(rdir: Path, gold: Path, thematic_only, combo_meta):
    data = yaml.safe_load(gold.read_text(encoding="utf-8"))
    if thematic_only is not None:
        data = [e for e in data if (e.get("entity_type") == "thematic") == thematic_only]
    qrels = {e["query"]: e["relevant_resolution_ids"] for e in data}
    queries = list(qrels)
    qi = {q: i for i, q in enumerate(queries)}
    arr: dict[str, np.ndarray] = {}
    for path in rdir.glob("*.json"):
        r = load_retrieval_result(path)
        if r.query not in qrels or r.combination_id not in combo_meta:
            continue
        a = arr.setdefault(r.combination_id, np.full(len(queries), np.nan))
        a[qi[r.query]] = recall_at_k(r, qrels[r.query], K)

    inv = {v: k for k, v in combo_meta.items()}
    ties = tot = 0
    diffs = []
    for e in EMBEDDER_ORDER:
        f, s = inv.get(("fixed_size", e)), inv.get(("semantic", e))
        if f not in arr or s not in arr:
            continue
        ok = ~(np.isnan(arr[f]) | np.isnan(arr[s]))
        d = (arr[f] - arr[s])[ok]
        ties += int((d == 0).sum())
        tot += int(ok.sum())
        diffs.append(float(d.mean()))

    per_ch: dict[str, list[float]] = defaultdict(list)
    per_em: dict[str, list[float]] = defaultdict(list)
    for cid, a in arr.items():
        c, e = combo_meta[cid]
        per_ch[c].append(float(np.nanmean(a)))
        per_em[e].append(float(np.nanmean(a)))

    order = lambda d, n=None: " > ".join(  # noqa: E731
        f"{k} {statistics.fmean(v):.3f}"
        for k, v in sorted(d.items(), key=lambda x: -statistics.fmean(x[1]))[:n]
    )
    return {
        "queries": str(len(queries)),
        "combos": str(len(arr)),
        "exact ties, fixed_size vs semantic": f"{ties}/{tot} = {ties / tot:.0%}" if tot else "-",
        "mean diff (fixed_size - semantic)": f"{statistics.fmean(diffs):+.4f}" if diffs else "-",
        "chunker order": order(per_ch),
        "embedder order": order(per_em, 4) + " ...",
    }


def main() -> None:
    combo_meta = build_combo_to_chunker_embedder(REPO / "data" / "index" / "chunker_compare_full")
    cols = []
    for label, rdir, gold, th in SETS:
        if not rdir.exists():
            print(f"missing results: {rdir}")
            return
        cols.append((label, measure(rdir, gold, th, combo_meta)))

    keys = list(cols[0][1])
    lines = [
        f"# Two gold query shapes on identical combos (dense recall@{K})",
        "",
        "Same 36 `chunker_compare_full` combos, same retriever, same metric -- only the",
        "query shape differs. Generated by `tools/eval/thematic_vs_deterministic.py`.",
        "",
        "| | " + " | ".join(label for label, _ in cols) + " |",
        "|---|" + "---|" * len(cols),
    ]
    for key in keys:
        lines.append(f"| {key} | " + " | ".join(c[key] for _, c in cols) + " |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwritten to {OUT}")


if __name__ == "__main__":
    main()
